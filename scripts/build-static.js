// Writes public/data.js: a copy of the menu and rules the site uses when no backend is reachable
// (for example on Netlify). Run after changing the menu or config: npm run build:static
import fs from "node:fs";
import { SEED_MENU } from "../src/db.js";
import { CAKE, SHOP, FESTIVE } from "../src/config.js";

const items = SEED_MENU.map(([id, cat, name, desc, g, p, egg, al]) => ({ id, cat, name, desc, g, p, egg: !!egg, al, soldOut: false }));
const data = {
  items,
  cake: { flavours: CAKE.flavours, sizes: CAKE.sizes, occasions: CAKE.occasions, minNoticeDays: CAKE.minNoticeDays },
  shop: { openMin: SHOP.openMin, lastSlotMin: SHOP.lastSlotMin, closedWeekday: SHOP.closedWeekday, maxDaysAhead: SHOP.maxDaysAhead },
  festive: FESTIVE,
};
fs.writeFileSync(new URL("../public/data.js", import.meta.url),
  "// Generated by scripts/build-static.js. Used only when the API isn't available.\nwindow.BLOOM_FALLBACK = " + JSON.stringify(data, null, 1) + ";\n");
console.log(`public/data.js written with ${items.length} items`);
